#!/usr/bin/env bash
# mkgremote.sh -- gremote-client, the host-side driver, as a wheel.
#
# WHY A PACKAGE OF ITS OWN. gremote is a client/server pair separate from
# the bridge and on a different port: GREMOTE.EXE listens on 7401 and this
# package connects to it, where the bridge listens on 7890 and GASTON.EXE
# connects to that. 0.4.0 shipped the server with no released client at
# all, so somebody who downloaded gremote-<ver>-win98.zip had nothing to
# drive it with but a git clone (BACKLOG 45).
#
# THE NAME SAYS WHICH HALF IT IS. The distribution is `gremote-client`;
# the import stays `gremote`. Those differing is ordinary -- pillow/PIL,
# beautifulsoup4/bs4 -- and keeping the import means none of the files
# under tests/ and research/ that say `from gremote import Remote` has to
# change.
#
# IT DEPENDS ON THE BRIDGE, and that is the code rather than the agent.
# Measured: a venv holding only gremote/ and bridge/, with no third-party
# package installed at all, imports `from gremote import Remote` and pulls
# exactly twelve bridge modules -- the wire format, the step compiler, the
# caps table. None reaches claude-agent-sdk, and Pillow is lazy inside
# Remote.png(). The honest expression of that today is a dependency on
# gaston-code-bridge; splitting those twelve into a shared distribution is
# the right answer and a real refactor (BACKLOG 45).
#
# STAGED INTO A TEMP DIRECTORY, because two distributions cannot share one
# directory's pyproject.toml and `..` in package-dir is not something
# setuptools should be asked to swallow.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$HERE/build/release"

usage() {
  cat >&2 <<USAGE
usage: mkgremote.sh [--out DIR]

  --out   default: build/release
USAGE
  exit 2
}
while [ $# -gt 0 ]; do
  case "$1" in
    --out)     OUT="${2:?}"; shift 2 ;;
    -h|--help) usage ;;
    *) echo "mkgremote: unknown argument $1" >&2; usage ;;
  esac
done

# One version for the whole release, read from the same file mkwheel.sh
# reads, so the two host-side wheels cannot disagree.
VERSION=$(sed -n 's/^version = "\([^"]*\)".*/\1/p' "$HERE/pyproject.toml" | head -1)
[ -n "$VERSION" ] || { echo "mkgremote: no version in pyproject.toml" >&2; exit 1; }

echo "=== gremote-client $VERSION, wheel ==="

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT" "$WORK/src"

cp -r "$HERE/gremote" "$WORK/src/gremote"
find "$WORK/src" -name '__pycache__' -type d -prune -exec rm -rf {} +
cp "$HERE/LICENSE" "$HERE/NOTICE" "$WORK/src/"

cat > "$WORK/src/pyproject.toml" <<TOML
# GENERATED by tools/gen/mkgremote.sh. Not checked in: it exists only
# inside a build, because the package it describes lives beside a
# different pyproject.toml in the repository.
[build-system]
requires = ["setuptools>=77"]
build-backend = "setuptools.build_meta"

[project]
name = "gremote-client"
version = "$VERSION"
description = "Drive a Windows 95/98/Me machine over the network: the host half of gremote"
readme = "README.md"
requires-python = ">=3.11"
license = "AGPL-3.0-only"
license-files = ["LICENSE", "NOTICE"]
authors = [{ name = "Tiberiu Chibici" }]
keywords = ["windows98", "retrocomputing", "remote-control", "automation"]

# The wire format, the step compiler and the caps table live in the bridge
# package and are what this reaches for. Twelve modules, none of which
# touches the agent SDK -- see the header of tools/gen/mkgremote.sh.
dependencies = ["gaston-code-bridge==$VERSION"]

[project.urls]
Homepage = "https://github.com/chibicitiberiu/gaston-code"
Source = "https://github.com/chibicitiberiu/gaston-code"

[tool.setuptools]
include-package-data = false
packages = ["gremote"]
TOML

cat > "$WORK/src/README.md" <<'MD'
# gremote-client

The host half of gremote: drive a Windows 95/98/Me machine over the
network. The other half is `GREMOTE.EXE`, which runs on the old machine
and is downloaded separately.

```python
from gremote import Remote

with Remote("192.168.1.50", secret="...") as r:
    print(r.hello["os"])
    r.exec(r"C:\WINDOWS\COMMAND\CSCRIPT.EXE //nologo x.vbs")
    open("screen.png", "wb").write(r.png())
```

It speaks a framed protocol over one TCP socket and needs no agent on the
old machine, which has none to run. See `docs/REMOTE.md` in the project.

**Licence: GNU AGPL v3 only.**
MD

echo "--- building (via sdist) ---"
python3 -m venv "$WORK/tools"
"$WORK/tools/bin/pip" install --quiet --upgrade pip build
"$WORK/tools/bin/python" -m build --outdir "$WORK/dist" "$WORK/src" >/dev/null

WHEEL=$(echo "$WORK"/dist/*.whl)
[ -f "$WHEEL" ] || { echo "mkgremote: no wheel built" >&2; exit 1; }

echo "--- checking ---"
LIST=$(unzip -Z1 "$WHEEL")
case "$(basename "$WHEEL")" in
  gremote_client-*-py3-none-any.whl) ;;
  *) echo "mkgremote: unexpected name $(basename "$WHEEL")" >&2; exit 1 ;;
esac
echo "    $(basename "$WHEEL")"

# The import name is `gremote` and must stay that way: sixteen files under
# tests/ and research/ say `from gremote import Remote`.
echo "$LIST" | grep -q "^gremote/client\.py$" || {
  echo "mkgremote: gremote/client.py is not in the wheel" >&2; exit 1; }
echo "    imports as gremote"

# AGPLv3 section 4. PEP 639 puts them under dist-info/licenses/.
for f in LICENSE NOTICE; do
  echo "$LIST" | grep -qE "^[^/]+\.dist-info/licenses/$f$" || {
    echo "mkgremote: $f missing from the wheel" >&2; exit 1; }
done
echo "    LICENSE and NOTICE under dist-info/licenses/"

# It must declare the bridge, or it installs and fails at the first import
# on a machine that has only this.
"$WORK/tools/bin/python" - "$WHEEL" <<'PY'
import re
import sys
import zipfile

names = zipfile.ZipFile(sys.argv[1]).namelist()
meta = next(n for n in names if n.endswith(".dist-info/METADATA"))
text = zipfile.ZipFile(sys.argv[1]).read(meta).decode()
if not re.search(r"^Requires-Dist: gaston-code-bridge==", text, re.M):
    sys.exit("mkgremote: the wheel does not require gaston-code-bridge, so "
             "it would install and then fail at `from gremote import Remote`")
print("    requires gaston-code-bridge")
PY

cp "$WHEEL" "$OUT/"
echo
echo "$(basename "$WHEEL")  --  $(stat -c%s "$WHEEL") bytes, $(echo "$LIST" | wc -l) files"
echo
echo "gremote-client $VERSION in $OUT"
