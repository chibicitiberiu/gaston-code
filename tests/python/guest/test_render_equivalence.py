"""The guest's renderer produces the bytes it is pinned to.

WHAT THIS WAS, AND WHAT IT IS NOW. Through stage 3 this ran the same
records through two renderers -- the guest's under Wine and the bridge's
`htmlrender.py` -- and compared them byte for byte. It was the most
valuable test of that stage: it is what turned "the guest emits the same
HTML MSHTML gets today" from an intention into a fact, and it found two
real bugs before it was even a test (text-mode stdout turning every `\n`
into `\r\n`, and a newline inside a payload line, which is a wire-format
violation no amount of reading either side would have shown).

Stage 3b deleted the bridge's emitter -- it was the last markup on the
bridge and the exit condition of stage 3 was that none be left. So the
expected bytes are CHECKED IN, generated from the last passing run of the
two-renderer proof, and this compares against those.

SAY PLAINLY THAT A FIXTURE IS WEAKER THAN A PROOF. It pins the renderer to
what it did on 2026-10-13 and nothing more. It can no longer catch a
renderer and an oracle drifting together, because there is no oracle -- but
there is also no second renderer to drift, which is the point of the stage.
What it still catches is any change to the guest's output, which is what it
is for now.

It runs the SHIPPED view.tpl, so the file in the repo stays pinned
byte-for-byte in a way view.css is not.

In guest/ because test_suite_hygiene.py requires the needs_guest mark for
anything touching the Wine plumbing.

THREE THINGS IT CANNOT PROVE, said here rather than implied:

  * That the markup is RIGHT. The fixture records what the renderer did,
    not what IE5 wants. That is what viewprobe's screenshots on the real
    guest are for.
  * That MSHTML parses it the same way.
  * That the fixture itself is right. It was generated by a renderer that
    agreed with the bridge's, which is the strongest statement available
    and is not the same as correct.
"""

from __future__ import annotations

import base64
import json
import os
import subprocess

import conftest
import pytest

from bridge.view import blocks as B

pytestmark = conftest.needs_guest

TEMPLATES = os.path.join(conftest.REPO, "win", "resources")
WRAPCOL = 56

#: The expected bytes, one entry per case, base64 because they are cp1252
#: and JSON is not.
FIXTURE = os.path.join(conftest.REPO, "tests", "goldens", "render",
                       "guest_render.json")

#: Rewrite the fixture FROM THE GUEST. Deliberately not the frame goldens'
#: mechanism, which writes a missing file silently (golden_utils.py:95) --
#: for this fixture that would mean a deleted file is re-blessed by the
#: renderer it is supposed to pin, and the test would go green having
#: proved nothing. A missing file is an error here, always.
UPDATE = os.environ.get("UPDATE_RENDER_FIXTURE") == "1"


def guest_render(data: bytes, wrapcol: int = WRAPCOL) -> bytes:
    """One frame body through the real renderer under Wine."""
    exe = conftest.guest_exe("rendercheck.exe")
    out = subprocess.run(
        [conftest.WINE, exe, "--template", TEMPLATES, "--render",
         "--wrapcol", str(wrapcol)],
        input=data, capture_output=True,
        env=dict(os.environ, WINEPREFIX=conftest.PREFIX, WINEDEBUG="-all"),
        timeout=120)
    assert out.returncode == 0, (
        f"rendercheck exited {out.returncode}\n"
        f"stdin: {data[:400]!r}\nstderr: {out.stderr[:800]!r}")
    return out.stdout


_fixture_cache: dict = {}
_written: dict = {}


def _fixture() -> dict:
    if not _fixture_cache:
        if not os.path.exists(FIXTURE):
            raise AssertionError(
                f"{FIXTURE} is missing. It is not regenerated automatically "
                f"-- see UPDATE in this file for why. Restore it from git.")
        with open(FIXTURE, encoding="ascii") as fh:
            _fixture_cache.update(json.load(fh))
    return _fixture_cache


def expected(key: str) -> bytes:
    f = _fixture()
    if key not in f:
        raise AssertionError(
            f"no fixture case {key!r}; the corpus changed without the "
            f"fixture. {len(f)} cases are recorded.")
    return base64.b64decode(f[key])


def check(key: str, body: bytes, wrapcol: int = WRAPCOL) -> None:
    """Render `body` on the guest and compare against the pinned bytes."""
    got = guest_render(body, wrapcol)
    if UPDATE:
        _written[key] = base64.b64encode(got).decode()
        return
    assert got == expected(key), key


# --- the corpus ---------------------------------------------------------
#
# test_html.py's inputs, plus the cases this stage added, plus the LIVE
# corpus -- which is NOT optional and is easy to miss. test_html.py's five
# LIVE tests assert on HTML, so they are not among the mechanical parser
# tests C2's split assumes; a partial block is a different Block from the
# sealed one (it carries _tail's elision marker and an unterminated run)
# and nothing else here would exercise one.

